#include "Point.hpp"

bool bsp( Point const a, Point const b, Point const c, Point const point) {
	Fixed Vab = 0;
	Fixed Vbc = 0;
	Fixed Vca = 0;

	Vab = (b.getX() - a.getX()) * (point.getY() - a.getY()) - (b.getY() - a.getY()) * (point.getX() - a.getX());
	Vbc = (c.getX() - b.getX()) * (point.getY() - b.getY()) - (c.getY() - b.getY()) * (point.getX() - b.getX());
	Vca = (a.getX() - c.getX()) * (point.getY() - c.getY()) - (a.getY() - c.getY()) * (point.getX() - c.getX());

	if ((Vab > 0 && Vbc > 0 && Vca > 0) || (Vab < 0 && Vbc < 0 && Vca < 0))
		return true;
	return false;
}